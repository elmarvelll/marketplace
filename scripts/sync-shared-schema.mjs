// scripts/sync-shared-schema.mjs  (npm run schema:sync   |   npm run schema:check)
//
// The Marketplace does not own the tables it shares with AkadVerse: their definition is AkadVerse's
// prisma/schema.prisma, and their migration history is AkadVerse's prisma/migrations. This script copies the shared
// models from that file into the region of prisma/schema.prisma between the BEGIN/END SHARED markers, so the two can't
// drift apart by hand-editing:
//   - only the models in SHARED_MODELS (and the enums they use) are copied, each verbatim, comments included;
//   - relation fields that point at models the Marketplace doesn't use (Task, Schedule, Skill, ...) are left out —
//     they are virtual in Prisma, so leaving them out changes no table;
//   - each copied block gets @@schema("public");
//   - User gets one extra (virtual) relation line to the Marketplace-owned AccountState.
// It only READS the AkadVerse file. --check exits 1 if prisma/schema.prisma is out of date (used by the tests).
//
// Source: $AKADVERSE_SCHEMA_PATH, default ../akadverse/prisma/schema.prisma (a sibling checkout of AkadVerse).

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = join(ROOT, "prisma/schema.prisma");
const BEGIN = "// ===== BEGIN SHARED — generated by scripts/sync-shared-schema.mjs from AkadVerse's prisma/schema.prisma. Do not edit by hand. =====";
const END = "// ===== END SHARED =====";

// Every AkadVerse table the Marketplace code reads or writes. Adding one here is not enough to use it: the runtime
// database role must also be granted access (db/runtime-grants.json), which is a reviewed change.
export const SHARED_MODELS = [
  "User",
  "Deliverer", "Delivery", "DeliveryItem", "Delivery_x_businesses", "OrderEvent", "BusinessDeliveryDay", "LateDeliveryFine",
  "Business", "Side", "BusinessVerificationRequest", "BusinessReport", "AdminActionLog", "MarketplaceSettings",
  "Product", "ProductImage", "VariantField", "VariantValue", "ProductVariant", "VariantValueOnProductVariant",
  "Order", "OrderItem", "CartItem", "CheckoutPayment", "VendorDeliveryBooking", "VendorDeliverySlot",
  "VendorTimeframeCapacity", "VendorTimeframeCapacityOverride", "VendorDeliveryDateOverride", "DelivererRosterAssignment",
  "Notification", "EmailDelivery",
];

const USER_EXTRA = "  // Marketplace-owned account state (schema \"marketplace\") — added by scripts/sync-shared-schema.mjs, not an AkadVerse column.\n  marketplaceAccount        AccountState?";

// Splits a Prisma schema into top-level blocks, each with the comment lines directly above it.
function parseBlocks(text) {
  const lines = text.split("\n");
  const blocks = [];
  let pendingComments = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const header = /^(model|enum|generator|datasource|type|view)\s+(\w+)\s*\{/.exec(line);
    if (header) {
      const body = [line];
      while (!/^\}/.test(lines[i])) body.push(lines[++i]);
      blocks.push({ kind: header[1], name: header[2], comments: pendingComments, body });
      pendingComments = [];
    } else if (/^\s*\/\//.test(line)) {
      pendingComments.push(line);
    } else if (line.trim() === "") {
      // A blank line ends a comment run that isn't attached to the next block.
      pendingComments = [];
    }
  }
  return blocks;
}

export function buildSharedRegion(akadverseSchema) {
  const blocks = parseBlocks(akadverseSchema);
  const models = new Map(blocks.filter((b) => b.kind === "model").map((b) => [b.name, b]));
  const enums = new Map(blocks.filter((b) => b.kind === "enum").map((b) => [b.name, b]));
  const missing = SHARED_MODELS.filter((m) => !models.has(m));
  if (missing.length) throw new Error(`AkadVerse's schema has no model(s): ${missing.join(", ")}`);

  const included = new Set(SHARED_MODELS);
  const usedEnums = new Set();
  const out = [];

  for (const block of blocks) {
    if (block.kind !== "model" || !included.has(block.name)) continue;
    const body = [];
    let droppedComments = [];
    for (const line of block.body.slice(1, -1)) {
      const field = /^\s+(\w+)\s+(\w+)(\[\])?(\?)?/.exec(line);
      if (field) {
        const type = field[2];
        if (models.has(type) && !included.has(type)) {
          droppedComments = [];
          continue; // relation to a model the Marketplace doesn't use: virtual, safe to omit
        }
        if (enums.has(type)) usedEnums.add(type);
      }
      if (/^\s*\/\//.test(line)) {
        droppedComments.push(line);
        continue;
      }
      body.push(...droppedComments, line);
      droppedComments = [];
    }
    body.push(...droppedComments);
    // Insert @@schema after the last field/attribute, keeping the closing brace.
    while (body.length && body[body.length - 1].trim() === "") body.pop();
    if (block.name === "User") {
      const firstAttr = body.findIndex((l) => /^\s+@@/.test(l));
      const at = firstAttr === -1 ? body.length : firstAttr;
      // Keep the blank line that conventionally separates fields from @@ attributes.
      const insertAt = at > 0 && body[at - 1].trim() === "" ? at - 1 : at;
      body.splice(insertAt, 0, USER_EXTRA);
    }
    body.push('  @@schema("public")');
    out.push([...block.comments, block.body[0], ...body, "}"].join("\n"));
  }

  for (const block of blocks) {
    if (block.kind !== "enum" || !usedEnums.has(block.name)) continue;
    const body = block.body.slice(1, -1);
    while (body.length && body[body.length - 1].trim() === "") body.pop();
    out.push([...block.comments, block.body[0], ...body, "", '  @@schema("public")', "}"].join("\n"));
  }

  return `${BEGIN}\n\n${out.join("\n\n")}\n\n${END}`;
}

export function syncedSchema(current, akadverseSchema) {
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (start === -1 || end === -1) throw new Error("prisma/schema.prisma has no BEGIN/END SHARED markers.");
  return current.slice(0, start) + buildSharedRegion(akadverseSchema) + current.slice(end + END.length);
}

function main() {
  const check = process.argv.includes("--check");
  const source = resolve(ROOT, process.env.AKADVERSE_SCHEMA_PATH || "../akadverse/prisma/schema.prisma");
  if (!existsSync(source)) {
    console.error(`✖ AkadVerse schema not found at ${source}. Set AKADVERSE_SCHEMA_PATH to AkadVerse's prisma/schema.prisma.`);
    process.exit(2);
  }
  const current = readFileSync(TARGET, "utf8");
  const next = syncedSchema(current, readFileSync(source, "utf8"));
  if (check) {
    if (next !== current) {
      console.error(`✖ prisma/schema.prisma is out of date with ${source}. Run npm run schema:sync and review the diff.`);
      process.exit(1);
    }
    console.log(`✔ Shared models match ${source}`);
    return;
  }
  writeFileSync(TARGET, next);
  console.log(`✔ Shared models copied from ${source}. Review the diff, then run npx prisma generate.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
